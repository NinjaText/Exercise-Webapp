/**
 * Regenerates lib/legal/documents/*.ts from the counsel-supplied Word files in
 * docs/legal/. The legal text is kept verbatim; this script only adds page
 * structure (section headings, anchors, links) around it.
 *
 *   node scripts/build-legal-docs.mjs
 *
 * After a new revision of either document: replace the .docx, run this, and
 * bump the matching version in lib/legal/versions.ts so new sign-ups record
 * which revision they accepted.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import mammoth from "mammoth";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = (f) => path.join(root, "docs/legal", f);
const out = (f) => path.join(root, "lib/legal/documents", f);

async function toHtml(file) {
  const { value, messages } = await mammoth.convertToHtml({ path: src(file) });
  const problems = messages.filter((m) => m.type !== "info");
  if (problems.length) console.warn(file, problems);
  return value;
}

/** Pulls "<strong>Label:</strong> value" header lines off the top of a document. */
function takeMeta(html, label) {
  const re = new RegExp(`<p><strong>${label}:</strong>\\s*([^<]*)</p>`);
  const m = html.match(re);
  return { value: m ? m[1].trim() : null, html: m ? html.replace(m[0], "") : html };
}

function structure(html, { links = [] } = {}) {
  let h = html;
  // Whole-paragraph bold "N. TITLE" → section heading; "N.N Title" → sub-heading.
  h = h.replace(/<p><strong>(\d+)\.\s+([^<]+)<\/strong><\/p>/g, (_, n, t) => `<h2 id="section-${n}">${n}. ${t.trim()}</h2>`);
  h = h.replace(
    /<p><strong>(\d+)\.(\d+)\s+([^<]+)<\/strong><\/p>/g,
    (_, a, b, t) => `<h3 id="section-${a}-${b}">${a}.${b} ${t.trim()}</h3>`,
  );
  // Tables scroll sideways on phones instead of widening the page.
  h = h.replace(/<table>/g, '<div class="legal-table"><table>').replace(/<\/table>/g, "</table></div>");
  // Bare email addresses → mailto links.
  h = h.replace(/(?<![">:/])\b([a-z]+@miaperformance\.com)\b/g, '<a href="mailto:$1">$1</a>');
  // Tidy the leading space Word leaves inside hyperlinks.
  h = h.replace(/<a href="([^"]+)">\s+/g, ' <a href="$1">');
  for (const [from, to] of links) h = h.split(from).join(to);
  return h.trim();
}

function emit(file, constName, doc) {
  const body = `// GENERATED by scripts/build-legal-docs.mjs from docs/legal/*.docx — do not edit by hand.
import type { LegalHtmlDocument } from "../types";

export const ${constName}: LegalHtmlDocument = ${JSON.stringify(doc, null, 2)};
`;
  writeFileSync(out(file), body);
  console.log("wrote", path.relative(root, out(file)));
}

function build(html, title, links) {
  let h = html.replace(/^<p><strong>[^<]+<\/strong><\/p>/, ""); // drop the all-caps title line
  const updated = takeMeta(h, "Last Updated");
  h = updated.html;
  const effective = takeMeta(h, "Effective Date");
  h = effective.html;
  h = h.replace(/<p><strong>Website:<\/strong>.*?<\/p>/, "");
  return { title, lastUpdated: updated.value, effectiveDate: effective.value, html: structure(h, { links }) };
}

// ── Terms of Use ────────────────────────────────────────────────────────────
const terms = await toHtml("terms-of-use.docx");
emit(
  "terms-of-use.ts",
  "TERMS_OF_USE",
  build(terms, "Terms of Use", [["[Privacy Policy]", '<a href="/privacy">Privacy Policy</a>']]),
);

// ── Privacy Policy + Consumer Health Data Privacy Policy (one Word file) ─────
const privacy = await toHtml("privacy-policy.docx");
const SPLIT = "<p><strong>MIA PERFORMANCE CONSUMER HEALTH DATA PRIVACY POLICY</strong></p>";
const at = privacy.indexOf(SPLIT);
if (at < 0) throw new Error("Consumer Health Data heading not found in privacy-policy.docx");

const chdLink = '<a href="/consumer-health-data">Consumer Health Data Privacy Policy</a>';
emit(
  "privacy-policy.ts",
  "PRIVACY_POLICY",
  build(privacy.slice(0, at), "Privacy Policy", [
    ["see also the Consumer Health Data Privacy Policy", `see also the ${chdLink}`],
    ["see our separate Consumer Health Data Privacy Policy", `see our separate ${chdLink}`],
  ]),
);

// The CHD notice has no "Last Updated" line of its own; it shares the policy's.
const chd = build(privacy.slice(at), "Consumer Health Data Privacy Policy", [
  ["Our general Privacy Policy", 'Our general <a href="/privacy">Privacy Policy</a>'],
]);
chd.lastUpdated ??= build(privacy.slice(0, at), "", []).lastUpdated;
emit("consumer-health-data.ts", "CONSUMER_HEALTH_DATA_POLICY", chd);
